#!/usr/bin/env python3
"""generate_api_grant_backfill.py - BRH-X (2026-10-21): write production's Data API grants into a migration, object by
object, so a replay of this schema reaches what production reaches.

Supabase's "Final notice" of 2026-10-20: from 2026-10-30 a new table in `public` gets no automatic grant to anon,
authenticated or service_role - for every new table, and for every replay of the schema (a local `supabase db reset`,
a preview branch, a new project). Measured the same day: of 247 public tables and views, 238 held API access that no
migration granted (most often service_role, which migrations had left to the automatic grant), so a replay after that
date would leave every page and every edge function refused.

Input: production's ACL for the three API roles, read once, read-only, through the claude.ai Supabase connector
(.tmp/mail/prod_acl.sql). Output: one migration whose DO block grants, for each object that EXISTS at that point of a
replay, exactly what production grants today - narrowed to what the Data API uses: SELECT/INSERT/UPDATE/DELETE on tables
and views and USAGE/SELECT/UPDATE on sequences for anon and authenticated; and for service_role every table privilege but
MAINTAIN (Postgres 17 only). An object created by a LATER migration carries its own GRANT there (the api-grants gate).

    python tools/generate_api_grant_backfill.py --acl .tmp/mail/prod_acl_raw.txt \
        --out supabase/migrations/20261015800000_brh_x_explicit_api_grants.sql
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

API_USER = {"r": {"SELECT", "INSERT", "UPDATE", "DELETE"}, "p": {"SELECT", "INSERT", "UPDATE", "DELETE"},
            "v": {"SELECT", "INSERT", "UPDATE", "DELETE"}, "m": {"SELECT"}, "S": {"USAGE", "SELECT", "UPDATE"}}
SERVICE = {"r": {"SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER"},
           "p": {"SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER"},
           "v": {"SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER"},
           "m": {"SELECT", "REFERENCES"}, "S": {"USAGE", "SELECT", "UPDATE"}}
ORDER = ["SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER", "USAGE"]


def read_acl(path: Path) -> list[tuple[str, str, str, set]]:
    raw = json.loads(path.read_text(encoding="utf-8"))["result"]
    body = raw[raw.index("[{"):raw.rindex("}]") + 2]
    out = []
    for r in json.loads(body):
        obj, kind, role, privs = r["line"].split("|")
        out.append((obj, kind, role, set(privs.split(","))))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--acl", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rows = []
    for obj, kind, role, privs in read_acl(Path(a.acl)):
        keep = privs & (SERVICE if role == "service_role" else API_USER).get(kind, set())
        if keep:
            rows.append((obj, kind, role, ", ".join(p for p in ORDER if p in keep)))
    rows.sort()
    values = ",\n".join(f"    ('{o}', '{k}', '{r}', '{p}')" for o, k, r, p in rows)
    objs = len({o for o, *_ in rows})
    sql = f"""-- BRH-X (2026-10-21): the Data API grants production holds today, written down - so a replay of this schema reaches
-- what production reaches after Supabase stops granting new tables automatically on 2026-10-30.
--
-- Supabase's "Final notice" of 2026-10-20: from 2026-10-30 a new table in `public` gets no automatic grant to anon,
-- authenticated or service_role, for every new table and for every replay of the schema - a local `supabase db reset`, a
-- preview branch, a new project. Measured 2026-10-21: of 247 public tables and views, 238 held API access that no
-- migration granted (service_role most often), so a replay after that date would refuse every page and edge function.
--
-- Generated by tools/generate_api_grant_backfill.py from production's ACL for the three API roles (read once, read-only,
-- through the claude.ai Supabase connector): {len(rows)} grants on {objs} tables, views and sequences, narrowed to what the
-- Data API uses - anon and authenticated get SELECT/INSERT/UPDATE/DELETE (USAGE/SELECT/UPDATE on sequences), never
-- TRUNCATE, REFERENCES, TRIGGER or MAINTAIN; service_role gets every table privilege but MAINTAIN. A replay comes out the
-- same as production for the API, and no wider.
--
-- In production this changes nothing (every grant is already there). In a replay it runs after the migrations that
-- created these objects; an object that does not exist yet at this point is skipped, and a migration that creates a
-- table or view later grants it itself (held by the api-grants gate).

do $$
declare
  r record;
begin
  for r in select * from (values
{values}
  ) as v(obj, kind, role, privs)
  loop
    if to_regclass('public.' || quote_ident(r.obj)) is null then
      continue;
    end if;
    execute format('grant %s on %s public.%I to %I', r.privs,
                   case when r.kind = 'S' then 'sequence' else 'table' end, r.obj, r.role);
  end loop;
end
$$;
"""
    Path(a.out).write_text(sql, encoding="utf-8")
    print(f"wrote {a.out}: {len(rows)} grants on {objs} objects")
    return 0


if __name__ == "__main__":
    sys.exit(main())
