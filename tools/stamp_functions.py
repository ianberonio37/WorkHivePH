#!/usr/bin/env python3
"""stamp_functions.py - every edge function knows which code it is, so a running one can be caught serving old code
(OWN AI failure-mode lens, "stale deploy cache", 2026-10-26).

A function can run code that is not the tree's and no gate sees it - every gate reads SOURCE. Locally the edge runtime's
compiled-module cache served yesterday's code through restarts ([[feedback_the_deno_cache_served_yesterdays_function]]);
in production a function edited or a _shared file changed and the function not redeployed runs the old code, and a
deploy that failed half-way leaves some functions old. Nothing could tell.

Each function's STAMP is sha256 over its own directory and the _shared files it imports, transitively (this generated
file excluded) - what its bundle holds - with line
endings normalised so a Windows checkout and the uploaded bundle agree; the first 12 hex. The stamps are written to
supabase/functions/_shared/build_stamps.ts, which every function bundles; _shared/health.ts reports the function's own
entry as `build` on /health. tools/verify_function_builds.py compares what a RUNNING function reports with the tree.

    python tools/stamp_functions.py --write    regenerate build_stamps.ts (before a deploy, after any function edit)
    python tools/stamp_functions.py --check    exit 1 when build_stamps.ts is not the tree's (the gate)
    python tools/stamp_functions.py --json     print {function: stamp} for the tree
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FN = ROOT / "supabase" / "functions"
SHARED = FN / "_shared"
OUT = SHARED / "build_stamps.ts"


def _files(d: Path) -> list[Path]:
    return sorted(p for p in d.rglob("*") if p.is_file() and p != OUT and "__pycache__" not in p.parts
                  and not p.name.startswith(".") and p.suffix not in (".pyc",))


def _feed(h, base: Path, files: list[Path]) -> None:
    for p in files:
        h.update(str(p.resolve().relative_to(base.resolve())).replace("\\", "/").encode())
        h.update(b"\0")
        h.update(p.read_bytes().replace(b"\r\n", b"\n"))
        h.update(b"\0")


def functions() -> list[str]:
    return sorted(d.name for d in FN.iterdir() if d.is_dir() and not d.name.startswith((".", "_")) and (d / "index.ts").exists())


_IMPORT = re.compile(r"""from\s+["'](\.{1,2}/[^"']+\.ts)["']|import\s*\(\s*["'](\.{1,2}/[^"']+\.ts)["']""")


def _shared_closure(name: str) -> list[Path]:
    """The _shared files this function's bundle can contain: every file it imports from _shared, and theirs, transitively.
    Hashing ALL of _shared made one new shared file stale every function at once - the stamp is what the bundle holds."""
    seen: set[Path] = set()
    todo = [p for p in _files(FN / name) if p.suffix in (".ts", ".js")]
    while todo:
        src = todo.pop()
        try:
            text = src.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for m in _IMPORT.finditer(text):
            dep = (src.parent / (m.group(1) or m.group(2))).resolve()
            if dep.parent == SHARED.resolve() and dep != OUT.resolve() and dep.exists() and dep not in seen:
                seen.add(dep)
                todo.append(dep)
    return sorted(seen)


def stamps() -> dict[str, str]:
    out = {}
    for name in functions():
        h = hashlib.sha256()
        _feed(h, FN, [p.resolve() for p in _files(FN / name)] + _shared_closure(name))
        out[name] = h.hexdigest()[:12]
    return out


def render(s: dict[str, str]) -> str:
    body = "\n".join(f'  "{k}": "{v}",' for k, v in s.items())
    return ("// GENERATED by tools/stamp_functions.py - do not edit by hand. Each function's stamp is sha256 over its own\n"
            "// directory and _shared (this file excluded), line endings normalised, first 12 hex. _shared/health.ts reports a\n"
            "// function's own entry as `build`; tools/verify_function_builds.py compares a running function with the tree, so\n"
            "// one serving old code (a stale runtime cache, a function not redeployed after a _shared change) is named.\n"
            "export const BUILD_STAMPS: Record<string, string> = {\n" + body + "\n};\n")


def main() -> int:
    s = stamps()
    if "--json" in sys.argv:
        print(json.dumps(s, indent=1))
        return 0
    want = render(s)
    have = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
    if "--write" in sys.argv:
        if have != want:
            OUT.write_text(want, encoding="utf-8", newline="\n")
        print(f"stamped {len(s)} functions -> {OUT.relative_to(ROOT)}")
        return 0
    stale = [k for k in s if f'"{k}": "{s[k]}"' not in have]
    print(f"function-stamps: {len(s) - len(stale)}/{len(s)} stamps current in {OUT.relative_to(ROOT)}")
    for k in stale[:12]:
        print(f"  - {k}: the tree is {s[k]}, the stamp file says otherwise - run tools/stamp_functions.py --write")
    print("PASS" if not stale else "FAIL")
    return 0 if not stale else 1


if __name__ == "__main__":
    sys.exit(main())
