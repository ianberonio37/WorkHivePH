#!/usr/bin/env python3
"""update_trajectory_scoreboard.py — regenerate the roadmap's HEADER scoreboard from the registry.

Ian (2026-08-24): "in our header of our roadmap, put completion percentage each trajectories so
that we have anti-drift discipline on the header of the roadmap." The discipline is structural:
this script is the ONLY writer of the block between the markers in UFAI_TRAJECTORY_ROADMAP.md,
the numbers come from trajectory_registry.json (the status SSOT), and
validate_trajectory_registry.py FAILS whenever the committed block differs from a fresh
regeneration — a hand-edited or stale scoreboard cannot survive a board run.

  (default)  rewrite the block in place
  --check    exit 1 if the committed block differs from the regeneration (used by the gate)
  --stdout   print the block only
"""
from __future__ import annotations

import io
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "trajectory_registry.json"
ROADMAP = ROOT / "UFAI_TRAJECTORY_ROADMAP.md"
START = "<!-- TRAJECTORY_SCOREBOARD_START (generated by tools/update_trajectory_scoreboard.py — do not hand-edit; the gate fails on drift) -->"
END = "<!-- TRAJECTORY_SCOREBOARD_END -->"

WAVE_NAMES = {
    "A": "Acquisition & first value", "B": "Field work phone-first", "C": "Supervisor ops",
    "D": "Cross-page chains & two-sided", "E": "Degraded conditions", "F": "Trust, language, access",
    "G": "Multi-hive & role diversity", "H": "Page depth: unwalked surfaces", "I": "AI features",
    "J": "Marketplace economy", "K": "Notifications & re-engagement", "L": "Device & context matrix",
    "M": "Data shape & scale", "N": "Concurrency & realtime", "O": "Search, SEO & arrival",
    "P": "Privacy, security & compliance", "Q": "Wayfinding & comprehension",
    "R": "Lifecycle & longitudinal", "S": "Infra degradation & release safety",
    # T201-T500 expansion (2026-08-31)
    "T": "Public Learn funnel", "U": "Public Tools funnel", "V": "Edge-function layer",
    "W": "Security & adversarial personas", "X": "Accessibility spectrum",
    "Y": "New human personas", "Z": "Data pathology deep",
    "AA": "Financial & economic edge", "AB": "Federation & multi-org",
    "AC": "Platform-evolution & longitudinal", "AD": "Ops & observability surfaces",
    "AE": "Compound systemic failures",
    # VEHICLE SEED (2026-09-02): the vehicle lane — solo owners + fleets on the same pages
    "VM": "Vehicle lane (solo + fleet)",
    "VD": "Real-document extraction proving ground",
    "VP": "Production deepwalk (personas x every page)",
}


def render() -> str:
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    ts = reg["trajectories"]
    from collections import Counter
    statuses = Counter(t["status"] for t in ts)
    # descoped rows (the T455-T470 org-federation tier — a product WorkHive is not) are EXCLUDED from
    # the to-100% denominator: "overall" measures 100% of what WorkHive IS, with the deferred count shown.
    scoped = [t for t in ts if t["status"] != "descoped"]
    descoped_n = len(ts) - len(scoped)
    overall = sum(t["pct"] for t in scoped) / len(scoped)
    lines = [START, ""]
    lines.append(f"**PROGRAM: {overall:.1f}% overall"
                 + (f" (of {len(scoped)} in-scope; {descoped_n} descoped = future org-federation tier)" if descoped_n else "")
                 + f" · {len(ts)} trajectories · "
                 + " · ".join(f"{v} {k}" for k, v in sorted(statuses.items(), key=lambda x: -x[1]))
                 + f"** — registry `trajectory_registry.json` (updated {reg['updated']}). "
                 "pct: specced 5 · walked 25 · fixed 60 · locked 100; in-flight carries a basis.")
    # THE CRITIC-DEEPWALK POINTER (Ian, 2026-09-02: "put it in your pointer in the header of roadmap
    # with percentage completion") — the UI/UX extension's live % sits HERE, in the first thing every
    # session reads, generated from critic_registry.json exactly like the line above (never typed).
    try:
        import json as _json, io as _io, os as _os
        _cp = _os.path.join(_os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))), "critic_registry.json")
        _c = _json.loads(_io.open(_cp, encoding="utf-8").read())
        _crows = _c["rows"]
        _cpct = {"pending": 0, "walked": 40, "critiqued": 70, "improving": 85, "locked": 100}
        _cst = Counter(r["status"] for r in _crows)
        _cov = sum(_cpct[r["status"]] for r in _crows) / max(len(_crows), 1)
        _cfind = sum(len(r.get("findings") or []) for r in _crows)
        lines.append("")
        lines.append(f"**↳ CRITIC DEEPWALK (UI/UX extension): {_cov:.1f}% · "
                     + " · ".join(f"{_cst[k]} {k}" for k in ("pending", "walked", "critiqued", "improving", "locked") if _cst.get(k))
                     + f" · {_cfind} receipted findings** — `UFAI_CRITIC_DEEPWALK_ROADMAP.md` / `critic_registry.json`; "
                     "walk → critique → fix → gate, every trajectory, until 100%.")
    except Exception:
        lines.append("")
        lines.append("**↳ CRITIC DEEPWALK (UI/UX extension): registry unreadable — run tools/validate_critic_registry.py**")
    lines.append("")
    lines.append("| Wave | Completion per trajectory |")
    lines.append("|---|---|")
    by_wave: dict[str, list[dict]] = {}
    for t in ts:
        by_wave.setdefault(t["wave"], []).append(t)
    # program order, not alphabetical — plain sorted() would file AA-AE between A and B.
    # Named waves (VM…, non-numeric ids) sort after the numeric program (★×16: the VM wave).
    def _order(w):
        ns = [int(m.group(1)) for t in by_wave[w] for m in [re.match(r"^T(\d+)$", t["id"])] if m]
        return min(ns) if ns else 10_000
    for w in sorted(by_wave, key=_order):
        cells = []
        for t in by_wave[w]:
            label = f"{t['id']}:{t['pct']}%"
            cells.append(f"**{label}**" if t["pct"] != 5 else label)
        wavg = sum(t["pct"] for t in by_wave[w]) / len(by_wave[w])
        lines.append(f"| **{w}** · {WAVE_NAMES[w]} ({wavg:.0f}%) | " + " · ".join(cells) + " |")
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    block = render()
    text = ROADMAP.read_text(encoding="utf-8") if ROADMAP.exists() else ""
    if START in text and END in text:
        pre = text[: text.index(START)]
        post = text[text.index(END) + len(END):]
        new = pre + block + post
    else:
        print("markers not found in the roadmap — the doc must carry the scoreboard block")
        return 1
    if "--check" in sys.argv:
        if new != text:
            print("SCOREBOARD DRIFT — the committed header no longer matches the registry. "
                  "Run: python tools/update_trajectory_scoreboard.py")
            return 1
        print("scoreboard current.")
        return 0
    if "--stdout" in sys.argv:
        print(block)
        return 0
    ROADMAP.write_text(new, encoding="utf-8")
    print("scoreboard regenerated in UFAI_TRAJECTORY_ROADMAP.md")
    return 0


if __name__ == "__main__":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    sys.exit(main())
