def _swap(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise SystemExit(f"build_operator_actions: platform-actions.html changed where the cut is made - expected exactly one of:\n{old[:200]}")
    return text.replace(old, new, 1)


def build() -> str:
    lines = SOURCE.read_text(encoding="utf-8").split("\n")
    start = next(i for i, l in enumerate(lines) if l.strip() == "const SUPABASE_URL = 'https://hzyvnjtisfgbksicrouu.supabase.co';")
    end = next(i for i in range(start, len(lines)) if lines[i].strip() == "</script>")
    body = "\n".join(lines[start:end])
    body = _swap(body, "    const SUPABASE_URL = 'https://hzyvnjtisfgbksicrouu.supabase.co';\n"
                       "    const SUPABASE_KEY = 'sb_publishable_ePj-suLMwkMRVDH6eM6S8g_R0rZVbMZ';\n"
                       "    const db = getDb(SUPABASE_URL, SUPABASE_KEY);\n",
                 "    const db = window.getDb();   // the console's own client (getDb returns the one already made)\n")
    body = _swap(body, "      const box = document.getElementById('toast');\n",
                 "      const box = document.getElementById('opc-toast') || document.getElementById('toast');\n")
    body = _swap(body, "        const [mod, tops, gcash, fb, cp, usage, decided] = await Promise.all([\n"
                       "          fetchMktModeration(), fetchSvcTopups(), fetchGcashLeftovers(),\n"
                       "          wantFeedback ? fetchFeedback() : Promise.resolve(null),\n"
                       "          fetchCreditPosition(), fetchUsage(), fetchDecisions()]);\n",
                 "        // the usage card's figures are the console's Growth Pulse panel (OPC): no usage reads from here\n"
                 "        const [mod, tops, gcash, fb, cp, decided] = await Promise.all([\n"
                 "          fetchMktModeration(), fetchSvcTopups(), fetchGcashLeftovers(),\n"
                 "          wantFeedback ? fetchFeedback() : Promise.resolve(null),\n"
                 "          fetchCreditPosition(), fetchDecisions()]);\n")
    body = _swap(body, "        renderUsage(usage);\n", "")
    a = body.index("    // The five founder rollups, read as ONE row of numbers.")
    end_usage = "      if (st) st.textContent = 'Updated ' + new Date().toLocaleTimeString('en-PH', { timeZone: 'Asia/Manila' });\n    }\n"
    b = body.index(end_usage, a) + len(end_usage)
    body = (body[:a] + "    // (The usage card's reads are not here: its one unique figure - what people used each page for - is drawn by the\n"
            "    // console's Growth Pulse panel, beside the daily and monthly actives it already shows.)\n" + body[b:])
    gate = "    // ── Admin gate (localhost bypass for the founder's own machine; server RLS still gates writes) ──\n"
    if body.count(gate) != 1:
        raise SystemExit("build_operator_actions: platform-actions.html's admin-gate marker moved - the cut needs it")
    body = body[:body.index(gate)]
    return HEADER + body.rstrip() + "\n" + GUARD + POST + FOOTER


def main() -> int:
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == build()
        print("PASS operator-actions.js is the current cut of platform-actions.html's queues" if ok
              else "FAIL operator-actions.js is not the current cut of platform-actions.html - run tools/build_operator_actions.py --out")
        return 0 if ok else 1
    if "--out" in sys.argv:
        OUT.write_text(build(), encoding="utf-8", newline="\n")
        print(f"wrote {OUT.name}")
        return 0
    print(build())
    return 0


if __name__ == "__main__":
    sys.exit(main())
