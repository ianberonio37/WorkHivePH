#!/usr/bin/env python3
"""build_operator_actions.py - the operator console's action queues, generated from their one source (OPC, 2026-10-22).

The money and moderation queues (credit position, GCash top-ups and the receipts the automatic match left, listing and
seller review, feedback triage, who decided what) are WRITTEN ONCE, in platform-actions.html's script, where they lived
while founder-console.html was retired and where every fix since 2026-08-03 landed - and where the ~28 gates that pin
their mechanisms (refusal sentences, confirms before money moves, honest counts, the hidden-tab refresh...) read them.
The console runs them from operator-actions.js, which this tool cuts from that script:

  * the client and the admin answer come from the console (it has already asked the server who this is): the page's
    own gate and boot are dropped, and start({ realAdmin }) runs the post-gate half - wire the queues, fill them, poll;
  * the module's toast is #opc-toast, so it and the console's toast never write one node;
  * the usage card is not carried: its one unique figure (what people used each page for) is the console's Growth
    Pulse panel's, beside the actives it already shows.

platform-actions.html itself is retired (its overlay sends a founder to the console, and its boot stops before any
queue loads), so the queues run in one place. Edit them in platform-actions.html, then regenerate.

    python tools/build_operator_actions.py --out      write operator-actions.js
    python tools/build_operator_actions.py --check    exit 1 when operator-actions.js is not the current cut
"""
