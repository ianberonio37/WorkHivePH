#!/usr/bin/env python3
"""render_figure_sources.py - SL D1 (2026-10-19): every figure says where it came from.

figure_sources.json is the curated registry: {page: [{sel, shows, basedOn, reads, whole?, chrome?, why?}]}. Each entry is
written from the page's own code - which read fills that element - never guessed from a name. This tool writes each
page's slice into the page itself, as <script type="application/json" id="wh-figure-sources"> just before </body>, so
the reveal in utils.js (whFigureSources) has it without another request, and a page served fresh always carries its
current sources. A data block is not executed, so it needs nothing from the CSP.

    python tools/render_figure_sources.py            # report pages whose block is missing, stale or orphaned
    python tools/render_figure_sources.py --apply    # write the blocks
    python tools/render_figure_sources.py --check    # the gate half (figure-sources-written): exit 1 on any drift
    python tools/render_figure_sources.py --self-test

Each entry also passes a shape check: a selector, what it shows, the view or RPC it reads (named in the database:
--check verifies every name against pg_class / pg_proc when the local database is up), and `why` on a chrome entry.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REG = ROOT / "figure_sources.json"
OPEN = '<script type="application/json" id="wh-figure-sources">'
BLOCK_RX = re.compile(r'\n?<!-- wh-figure-sources: generated by tools/render_figure_sources.py from figure_sources.json - do not edit -->\n'
                      r'<script type="application/json" id="wh-figure-sources">[\s\S]*?</script>\n?')
HEAD = '<!-- wh-figure-sources: generated by tools/render_figure_sources.py from figure_sources.json - do not edit -->'


def load_registry() -> dict:
    if not REG.exists():
        return {}
    d = json.loads(REG.read_text(encoding="utf-8"))
    return {k: v for k, v in d.items() if not k.startswith("_")}


def block_for(entries: list) -> str:
    slim = [{k: e[k] for k in ("sel", "shows", "basedOn", "reads", "whole", "chrome") if k in e} for e in entries]
    return HEAD + "\n" + OPEN + json.dumps(slim, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/") + "</script>\n"


def shape_problems(page: str, entries: list) -> list:
    bad = []
    for i, e in enumerate(entries):
        where = f"{page}[{i}] {e.get('sel')!r}"
        if not e.get("sel"):
            bad.append(f"{where}: no selector")
        if e.get("chrome"):
            if not e.get("why"):
                bad.append(f"{where}: a chrome entry must say why the number is not data")
            continue
        if not e.get("shows"):
            bad.append(f"{where}: says nothing about what it shows")
        if not e.get("reads"):
            bad.append(f"{where}: names no view or RPC it reads")
    return bad


def db_names() -> set | None:
    try:
        r = subprocess.run(["docker", "exec", "supabase_db_workhive", "psql", "-U", "postgres", "-d", "postgres", "-At", "-c",
                            "select relname from pg_class where relnamespace='public'::regnamespace and relkind in ('r','v','m') "
                            "union select proname from pg_proc where pronamespace='public'::regnamespace"],
                           capture_output=True, text=True, encoding="utf-8", timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    if r.returncode:
        return None
    return {ln.strip() for ln in r.stdout.splitlines() if ln.strip()}


def read_names(e: dict) -> list:
    return [x for x in re.split(r"\s*[,+]\s*", str(e.get("reads") or "")) if x and re.match(r"^[a-z_][a-z0-9_]*$", x)]


def run(apply: bool) -> int:
    reg = load_registry()
    problems, wrote = [], []
    for page, entries in sorted(reg.items()):
        problems += shape_problems(page, entries)
    # a figure measured from a file the page fetches (design-system's centralization axes read four baselines) names
    # the file: it must be a file the site actually serves, not a name nobody can open
    for page, entries in reg.items():
        for e in entries:
            for n in re.split(r"\s*[,+]\s*", str(e.get("reads") or "")):
                if n.endswith(".json") and not (ROOT / n).is_file():
                    problems.append(f"{page} {e.get('sel')!r}: reads {n!r}, which is no file the site serves")
    names = db_names()
    if names is not None:
        for page, entries in reg.items():
            for e in entries:
                for n in read_names(e):
                    if n not in names:
                        problems.append(f"{page} {e.get('sel')!r}: reads {n!r}, which is no table, view or function in the database")
    pages = sorted(set(reg) | {p.name for p in ROOT.glob("*.html") if OPEN in p.read_text(encoding="utf-8", errors="replace")})
    for page in pages:
        p = ROOT / page
        if not p.exists():
            problems.append(f"{page}: in figure_sources.json but no such page")
            continue
        src = p.read_text(encoding="utf-8")
        want = block_for(reg[page]) if page in reg and reg[page] else ""
        have_m = BLOCK_RX.search(src)
        have = have_m.group(0).strip("\n") + "\n" if have_m else ""
        if have == want:
            continue
        if not apply:
            problems.append(f"{page}: its figure-sources block is {'missing' if want and not have else 'orphaned' if have and not want else 'stale'} (--apply)")
            continue
        new = BLOCK_RX.sub("\n", src) if have_m else src
        if want:
            i = new.rfind("</body>")
            if i < 0:
                problems.append(f"{page}: no </body> to write before")
                continue
            new = new[:i].rstrip("\n") + "\n" + want + new[i:]
        p.write_text(new, encoding="utf-8", newline="")
        wrote.append(page)
    for x in problems:
        print("  FAIL", x)
    if apply and wrote:
        print("wrote", len(wrote), "page(s):", ", ".join(wrote))
    n_fig = sum(1 for es in reg.values() for e in es if not e.get("chrome"))
    if problems:
        print(f"FAIL figure-sources-written - {len(problems)} problem(s)")
        return 1
    print(f"PASS figure-sources-written - {len(reg)} page(s), {n_fig} figure source(s) written into their pages, every "
          f"one naming what it shows and the view it reads{'' if names is None else ' (each read checked in the database)'}")
    return 0


def self_test() -> int:
    ok = True
    good = [{"sel": "#stat-total", "shows": "Parts", "basedOn": "x", "reads": "v_inventory_items_truth"}]
    cases = [("a full entry passes", shape_problems("p", good), False),
             ("no reads is caught", shape_problems("p", [{"sel": "#a", "shows": "x"}]), True),
             ("a chrome entry without why is caught", shape_problems("p", [{"sel": "#a", "chrome": True}]), True),
             ("a chrome entry with why passes", shape_problems("p", [{"sel": "#a", "chrome": True, "why": "step dot"}]), False)]
    blk = block_for(good)
    cases.append(("the block round-trips", [] if BLOCK_RX.search("\n" + blk) else ["no match"], False))
    cases.append(("a script close inside text is escaped", [] if "<\\/" in block_for([{"sel": "#a", "shows": "</script>", "reads": "x"}]) else ["raw"], False))
    for label, got, want_bad in cases:
        hit = bool(got)
        print(f"  {'ok ' if hit == want_bad else 'BAD'} {label}")
        ok &= hit == want_bad
    print("SELF-TEST " + ("PASS" if ok else "FAIL"))
    return 0 if ok else 1


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    if "--self-test" in sys.argv:
        sys.exit(self_test())
    sys.exit(run(apply="--apply" in sys.argv))
