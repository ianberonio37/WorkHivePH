#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""fix_calc_cta_crew_context.py — the 60 calculator CTAs told a technician what they'd GET, not what it means for the work.

FOUND 2026-10-05 by the CA-layer walk (`prove_w4_layer_ca.mjs --axis "phone-390 en"`), which reads each page's
VISIBLE copy and asks whether it uses the words a Philippine maintenance crew uses. 57 of the 60 generated
calculator pages scored 1-3 against a floor of 4 — and all 57 reported the SAME count, which is what pointed at
one shared template rather than at 57 pages ([[feedback_a_family_that_measures_identically_is_a_reason_to_read_the_generator]]).

The old sentence: "Free, and a free sign-up saves your calculations, BOMs and scope-of-works to your account."
True, and it answers a question nobody asked. A maintenance engineer who found this page from a search wants to
know what it does for the JOB.

★EVERY CLAUSE OF THE NEW SENTENCE WAS CHECKED AGAINST THE SCHEMA, and the draft I had before checking was FALSE.
I was about to write "ties them to the asset, the PM schedule and the work order" — `engineering_calcs` has no
asset_id and no project_id at all. It carries hive_id, worker_name, project_name (text), bom_data, sow_text, and
`engineering_calcs_read` admits any ACTIVE member of that hive. So what the sentence now claims is exactly what
the table does, and nothing more. Measured when written: 31 of 31 rows carry a project_name, 30 carry bom_data,
30 carry sow_text.

★WHY A SWEEP AND NOT JUST THE GENERATOR. `tools/build_calc_pages.py` writes to seo_assets/calc_pages_staging,
NOT to the served pages, and `prove_calc_staging_not_stale` exists precisely because promoting that directory
would revert work already fixed live. The served pages are AHEAD of the template — their CTA already reads
". Free, and a" where the template says " — free; a" — so the live wording is the source of truth
([[feedback_the_prose_was_stale_the_registry_was_right]]). The template is updated too, so a future build
carries the same sentence, but the live fix has to be its own idempotent sweep.

★AND IT IS A PAIRED WRITE. Each page has a markdown twin at `tools/<slug>/index.html.md` (the llms.txt
convention) carrying the same prose, generated by tools/build_md_twins.py. Fixing only the HTML would leave 60
twins asserting the old copy to every agent that fetches them, so --apply rebuilds the twins as its last step.

  python tools/fix_calc_cta_crew_context.py --check
  python tools/fix_calc_cta_crew_context.py --apply
"""
from __future__ import annotations

import io
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GREEN, RED, YEL, RST = "\033[92m", "\033[91m", "\033[93m", "\033[0m"

# ★AND THE SENTENCE THAT FIXED THE MEANING WAS 47 WORDS LONG (critic B3, 2026-10-13). The crew-context rewrite
# below was right about every clause and packed all of them into one sentence, which B3 (20 words or fewer,
# grade 8 or lower) failed on 58 pages. Same clauses, same schema-checked claims, four short sentences. Every
# earlier wording is an OLD, so a page still carrying either one is migrated and --check still bites on it.
OLDS = (
    "Free, and a free sign-up saves your calculations, BOMs and scope-of-works to your account.",
    "Free, and a free sign-up saves the calculation, its bill of materials and its scope of works to your "
    "hive under the project name your team already uses, so the next technician on that job reads the same "
    "numbers instead of re-deriving them.",
)
OLD = OLDS[0]   # kept for readers of the history above
NEW = ("Free to use. A free account saves the calculation, its bill of materials and its scope of works to your "
       "hive. Your team finds them under the project name it already uses. The next technician on that job reads "
       "the same numbers instead of re-deriving them.")
# what prove_calc_staging_not_stale asks: a fragment every retired wording carries and NEW does not, so the
# generator-era variant ("— free. A free sign-up saves ...") is caught as well as the two served ones
RETIRED_MARKERS = ("saves your calculations, BOMs and scope-of-works",
                   "under the project name your team already uses, so the next technician")


def retired_count(text: str) -> int:
    # rendered copy only: the generator's own HTML comment QUOTES the first wording to explain the change, and a
    # comment is not a sentence anyone reads
    import re
    return sum(re.sub(r"<!--.*?-->", "", text, flags=re.S).count(m) for m in RETIRED_MARKERS)


def pages() -> list[Path]:
    return sorted(p for p in ROOT.glob("tools/*/index.html") if p.is_file())


def main() -> int:
    check = "--check" in sys.argv
    apply = "--apply" in sys.argv
    if not (check or apply):
        print(__doc__)
        return 0

    todo, done, absent = [], [], []
    for p in pages():
        s = io.open(p, encoding="utf-8").read()
        if NEW in s:
            done.append(p)
        elif any(o in s for o in OLDS):
            todo.append(p)
        else:
            absent.append(p)

    print(f"  calc CTA crew context: {len(todo)} to fix · {len(done)} already carry it · "
          f"{len(absent)} have neither sentence")
    for p in absent[:4]:
        print(f"    note  {p.relative_to(ROOT)} carries neither wording - left untouched rather than guessed at")

    if check:
        if todo:
            print(f"{RED}FAIL{RST} calc-cta-crew-context - {len(todo)} calculator CTA(s) still carry an earlier "
                  f"wording (what they GET, or the one 47-word sentence) (run --apply)")
            return 1
        print(f"{GREEN}PASS{RST} calc-cta-crew-context - every calculator CTA names the hive, the project and the "
              f"next technician, which is what the page's reader came for ({len(done)} page(s))")
        return 0

    changed = 0
    for p in todo:
        s = io.open(p, encoding="utf-8").read()
        for o in OLDS:
            s = s.replace(o, NEW)
        tmp = p.with_suffix(".html.tmp")
        io.open(tmp, "w", encoding="utf-8", newline="\n").write(s)
        tmp.replace(p)                      # atomic: open(w) truncates before the write
        changed += 1
    print(f"  rewrote {changed} CTA(s)")

    # the PAIRED half: the markdown twins carry the same prose to every agent that fetches them
    if changed:
        twin = ROOT / "tools" / "build_md_twins.py"
        if twin.exists():
            r = subprocess.run([sys.executable, str(twin)], capture_output=True, text=True,
                               timeout=600, encoding="utf-8", errors="replace")
            tail = [ln for ln in (r.stdout or "").splitlines() if ln.strip()]
            print(f"  md twins: {'ok' if r.returncode == 0 else 'WARN'} {(tail[-1] if tail else '')[:92]}")
        else:
            print(f"  {YEL}WARN{RST} tools/build_md_twins.py is missing - the 60 .md twins still assert the old "
                  f"copy to every agent that fetches them")
    stale = [p for p in pages()
             if (p.parent / "index.html.md").exists()
             and any(o in io.open(p.parent / "index.html.md", encoding="utf-8").read() for o in OLDS)]
    if stale:
        print(f"  {RED}{len(stale)} markdown twin(s) still carry the old sentence{RST}")
        return 1
    print(f"{GREEN}done{RST} - {changed} page(s) and their markdown twins now say what the calculation is for")
    return 0


if __name__ == "__main__":
    if sys.platform == "win32":
        sys.stdout = io.TextIOWrapper(sys.stdout.detach(), encoding="utf-8", errors="replace")
    raise SystemExit(main())
