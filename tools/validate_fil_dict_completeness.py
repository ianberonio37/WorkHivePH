#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""validate_fil_dict_completeness.py — every AUTHORED page dictionary is fully translated, forward-only.

WHAT THIS IS FOR, and why `i18n-coverage` does not already do it. That gate counts i18n MARKERS per page
(`data-i=`, `_t(`, `whT(`) as an adoption proxy and says so in its own label: "marker COUNT is an adoption
proxy, not exact translated/total %". It is also advisory and always exits 0. So nothing was asserting the
thing that actually decides whether a Filipino worker reads Filipino: that the authored dictionary behind
each page has a value for every key it declares.

MEASURED 2026-10-05, driving the CA layer to its end: 1,069 of 1,338 strings were translated (79.9%), and
the shape of the gap was the point — `hive.json`, the most-used page on the platform, sat at **2 of 78**.
A key with an empty value is not a neutral placeholder: `wh-i18n-lite` finds no translation and renders the
English, so the page shows a Filipino skip link, Filipino buttons, and an English heading between them, and
nothing anywhere reports it. (That exact defect is on record from the 2026-09-11 Filipino round.) After
authoring, all 37 dictionaries read 1,440/1,440.

THE RATCHET IS THE WHOLE POINT. 100% reached once decays the first time anyone adds a string — the dict
gains a key with an empty value and the page quietly goes half-English. So the baseline stores the number
of UNTRANSLATED strings and may only fall. At 0, any new key must be authored in the same change, which is
the only moment when whoever wrote the English still knows what it means.

★AN EMPTY STRING IS A DELIBERATE STATE IN THIS SCHEMA - the `_doc` of every dict says "Empty = not yet
translated" - so this gate reads emptiness exactly as the format defines it rather than inventing a rule.
It never guesses a translation and never writes to a dict; it only refuses to let the count grow.

  python tools/validate_fil_dict_completeness.py            # report
  python tools/validate_fil_dict_completeness.py --check     # the gate
  python tools/validate_fil_dict_completeness.py --selftest  # proves it bites
"""
from __future__ import annotations

import glob
import io
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "fil_dict_completeness_baseline.json"
GREEN, RED, YEL, RST = "\033[92m", "\033[91m", "\033[93m", "\033[0m"


def dicts() -> list[Path]:
    """The AUTHORED dictionaries only.

    `i18n/pages/*.fil.json` is GENERATED by tools/i18n_page_dict.py --apply from these, so counting it would
    double-count and would also make the gate red for a reason nobody can fix by authoring - the fix there is
    to re-run the applier, which is a different failure.
    """
    out = []
    for p in sorted(glob.glob(str(ROOT / "i18n" / "**" / "*.json"), recursive=True)):
        q = Path(p)
        if (os.sep + "pages" + os.sep) in p:
            continue
        if q.name.endswith(".fil.json"):
            continue
        out.append(q)
    return out


def scan() -> tuple[int, int, list[tuple[str, str]]]:
    total = translated = 0
    missing: list[tuple[str, str]] = []
    for p in dicts():
        try:
            d = json.loads(io.open(p, encoding="utf-8").read())
        except Exception:                                      # noqa: BLE001
            continue
        if not isinstance(d, dict):
            continue
        for k, v in d.items():
            if k == "_doc":
                continue
            total += 1
            if isinstance(v, str) and v.strip():
                translated += 1
            else:
                missing.append((str(p.relative_to(ROOT)), k))
    return total, translated, missing


def runtime_gap() -> list[tuple[str, int, int]]:
    """Authored Filipino that a reader cannot actually reach.

    ★AN AUTHORED TRANSLATION THAT NEVER REACHES THE PAGE IS WRITE-ONLY. `utils.js` fetches the RUNTIME dict,
    `i18n/pages/<stem>.fil.json`, once per page under FIL - it does NOT read `i18n/<stem>.json`, which is the
    authored source that tools/i18n_page_dict.py --apply publishes INTO it. So a dict can read 100% translated
    while the page still shows English, and the completeness clause above would call that green.
    (I nearly reported this backwards: my first probe looked for an INLINE `window.WH_FIL_PAGE` object, found
    none on 29 pages, and concluded the work was unpublished - the loader fetches a file instead, so the reader
    was the wrong oracle, not the pages. Measure the path the runtime actually takes.)
    Measured when this was written: 25 pages, 199 authored strings not yet reachable."""
    out = []
    for p in dicts():
        stem = p.stem
        if not (ROOT / (stem + ".html")).exists():
            continue
        try:
            d = json.loads(io.open(p, encoding="utf-8").read())
        except Exception:                                      # noqa: BLE001
            continue
        authored = sum(1 for k, v in d.items() if k != "_doc" and isinstance(v, str) and v.strip())
        rt = ROOT / "i18n" / "pages" / (stem + ".fil.json")
        n = 0
        if rt.exists():
            try:
                r = json.loads(io.open(rt, encoding="utf-8").read())
                n = len(r) if isinstance(r, dict) else 0
            except Exception:                                  # noqa: BLE001
                n = 0
        if n < authored:
            out.append((stem, authored, n))
    return out


def main() -> int:
    check = "--check" in sys.argv
    if "--selftest" in sys.argv:
        return selftest()

    if "--runtime" in sys.argv:
        gap = runtime_gap()
        short = sum(a - n for _, a, n in gap)
        for stem, a, n in sorted(gap, key=lambda r: -(r[1] - r[2]))[:12]:
            print(f"    {a - n:4} unreachable  {stem:28} authored {a:3} · runtime {n:3}")
        if gap:
            print(f"{RED}FAIL{RST} fil-dict-runtime — {short} authored Filipino string(s) across {len(gap)} page(s) "
                  f"are not in the RUNTIME dict utils.js fetches (i18n/pages/<page>.fil.json), so the page still "
                  f"shows English. Publish them: python tools/i18n_page_dict.py --apply <page>")
            return 1
        print(f"{GREEN}PASS{RST} fil-dict-runtime — every authored string is present in the runtime dict the "
              f"page actually fetches")
        return 0
    total, translated, missing = scan()
    pct = (100.0 * translated / total) if total else 100.0
    print(f"  authored Filipino: {translated}/{total} string(s) across {len(dicts())} page dict(s) ({pct:.1f}%)")
    per: dict[str, int] = {}
    for f, _ in missing:
        per[f] = per.get(f, 0) + 1
    for f, n in sorted(per.items(), key=lambda kv: -kv[1])[:10]:
        print(f"    {n:4} untranslated  {f}")
    for f, k in missing[:6]:
        print(f"      e.g. {f}: {json.dumps(k, ensure_ascii=False)[:96]}")

    count = len(missing)
    if not BASELINE.exists():
        BASELINE.write_text(json.dumps({"untranslated": count, "established": "2026-10-05",
                                        "note": "forward-only: author new strings in the same change that adds "
                                                "them. An empty value renders ENGLISH, which is the defect."},
                                       indent=1) + "\n", encoding="utf-8")
        print(f"BASELINE established: {count} untranslated string(s) (forward-only)")
        return 0
    base = json.loads(BASELINE.read_text(encoding="utf-8")).get("untranslated", 0)
    if count > base:
        print(f"{RED}FAIL{RST} fil-dict-completeness — untranslated strings GREW {base} -> {count}. A key with an "
              f"empty value renders the ENGLISH, so these pages now show a mix; author them in the change that "
              f"added them, while the English is still fresh.")
        return 1
    if count < base:
        BASELINE.write_text(json.dumps({"untranslated": count, "ratcheted": "auto"}, indent=1) + "\n",
                            encoding="utf-8")
        print(f"{GREEN}PASS{RST} fil-dict-completeness — improved {base} -> {count}; ratchet lowered.")
        return 0
    if count == 0:
        print(f"{GREEN}PASS{RST} fil-dict-completeness — every authored string in all {len(dicts())} page "
              f"dictionaries has Filipino ({translated}/{total}); the ratchet holds at 0.")
    else:
        print(f"{GREEN}PASS{RST} fil-dict-completeness — held at {count} untranslated (baseline {base}).")
    return 0


def selftest() -> int:
    """It must FAIL on a new empty value and PASS once it is authored."""
    import tempfile
    probe = ROOT / "i18n" / "_selftest_probe.json"
    if probe.exists():
        probe.unlink()
    base_total, base_tr, base_missing = scan()
    probe.write_text(json.dumps({"_doc": "selftest", "A brand new English string": ""}, indent=1) + "\n",
                     encoding="utf-8")
    t2, tr2, m2 = scan()
    grew = len(m2) == len(base_missing) + 1
    probe.write_text(json.dumps({"_doc": "selftest", "A brand new English string": "Isang bagong teksto"},
                                indent=1) + "\n", encoding="utf-8")
    t3, tr3, m3 = scan()
    authored = len(m3) == len(base_missing)
    probe.unlink()
    t4, tr4, m4 = scan()
    restored = (t4, tr4, len(m4)) == (base_total, base_tr, len(base_missing))
    ok = grew and authored and restored
    print(f"  selftest: empty value counted={grew} · authored value clears it={authored} · probe removed "
          f"cleanly={restored}")
    print(("PASS" if ok else "FAIL") + " fil-dict-completeness selftest")
    return 0 if ok else 1


if __name__ == "__main__":
    if sys.platform == "win32":
        sys.stdout = io.TextIOWrapper(sys.stdout.detach(), encoding="utf-8", errors="replace")
    raise SystemExit(main())
